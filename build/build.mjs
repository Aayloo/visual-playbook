#!/usr/bin/env node
/**
 * Build script for Visual Playbook.
 *
 * Source of truth : data/cases.json
 * Outputs         : gallery/index.html          (self-contained, bilingual)
 *                   references/cases.md         (Chinese checklist)
 *                   references/cases.en.md      (English checklist)
 *
 * Run from the repository root:  node build/build.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => {
  const abs = path.join(root, p);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, s, 'utf8');
  return abs;
};

const data = JSON.parse(read('data/cases.json'));
const items = data.categories.flatMap(c => c.items);
const T = (v, lang) => (v == null ? '' : typeof v === 'string' ? v : v[lang] || v.zh || '');

/* ---------- 1. gallery/index.html ---------- */

const template = read('build/template.html');
const payload = JSON.stringify(data).replace(/<\//g, '<\\/');
const html = template.replace('/*__DATA__*/', payload);
write('gallery/index.html', html);

/* ---------- 2. references/cases.md ---------- */

const LABELS = {
  zh: {
    title: '视觉呈现素材库',
    checked: '核对日期',
    intro: '本文件由 `build/build.mjs` 从 `data/cases.json` 生成，请不要直接编辑。',
    index: '目录',
    family: { approach: '做法', reference: '参考' },
    cols: ['名称', '类型', '星数', '为什么值得看', '可以抄什么'],
    type: { oss: '开源', site: '网站', tool: '工具', org: '机构', product: '成品' },
    footnote: [
      '星数为核对当日的 GitHub 实时数据。',
      '标 `—` 的表示不是开源项目，没有星数。',
      '个别站点会拦截自动访问，浏览器里正常可以打开。'
    ]
  },
  en: {
    title: 'Visual Playbook',
    checked: 'Checked',
    intro: 'Generated by `build/build.mjs` from `data/cases.json`. Do not edit this file directly.',
    index: 'Contents',
    family: { approach: 'Approach', reference: 'Reference' },
    cols: ['Name', 'Type', 'Stars', 'Why it is worth a look', 'What to copy'],
    type: { oss: 'Open source', site: 'Site', tool: 'Tool', org: 'Studio', product: 'Product' },
    footnote: [
      'Star counts are GitHub data as of the date checked.',
      'A dash means the entry is not an open-source project and has no star count.',
      'A few sites block automated requests but open normally in a browser.'
    ]
  }
};

const anchor = s => s.toLowerCase().replace(/[^a-z0-9\u4e00-\u9fa5 -]/g, '').replace(/\s+/g, '-');

function markdownFor(lang) {
  const L = LABELS[lang];
  const out = [];
  out.push('# ' + L.title + ' / ' + LABELS[lang === 'zh' ? 'en' : 'zh'].title);
  out.push('');
  out.push('> ' + T(data.meta.tagline, lang));
  out.push('>');
  out.push('> ' + L.checked + ': ' + data.meta.date + ' &nbsp;|&nbsp; ' + items.length + ' ' +
    (lang === 'zh' ? '条目' : 'entries') + ' &nbsp;|&nbsp; ' + data.categories.length + ' ' +
    (lang === 'zh' ? '分类' : 'categories'));
  out.push('');
  out.push(T(data.meta.intro, lang));
  out.push('');
  out.push('**' + T(data.meta.rule, lang) + '**');
  out.push('');
  out.push('---');
  out.push('');
  out.push('## ' + L.index);
  out.push('');
  data.categories.forEach(c => {
    out.push('- [' + c.no + ' ' + T(c.name, lang) + '](#' + c.no + '-' + anchor(T(c.name, lang)) + ') — ' +
      c.items.length + ' ' + (lang === 'zh' ? '条' : 'entries'));
  });
  out.push('');
  out.push('---');
  out.push('');

  ['approach', 'reference'].forEach(fam => {
    out.push('## ' + L.family[fam] + ' / ' + LABELS[lang === 'zh' ? 'en' : 'zh'].family[fam]);
    out.push('');
    out.push('_' + T(data.families[fam].desc, lang) + '_');
    out.push('');
    data.categories.filter(c => c.family === fam).forEach(c => {
      out.push('### ' + c.no + ' ' + T(c.name, lang));
      out.push('');
      out.push(T(c.desc, lang));
      out.push('');
      const subs = c.subs || [];
      const groups = subs.length
        ? subs.map(sb => ({ title: T(sb.name, lang), items: c.items.filter(i => i.sub === sb.id) })).filter(g => g.items.length)
        : [{ title: null, items: c.items }];
      groups.forEach(g => {
        if (g.title) { out.push('#### ' + g.title); out.push(''); }
        out.push('| ' + L.cols.join(' | ') + ' |');
        out.push('| --- | --- | --- | --- | --- |');
        g.items.forEach(i => {
          const name = '[' + i.name + '](' + i.url + ')';
          out.push('| ' + [name, L.type[i.type] || i.type, i.stars || '—', T(i.why, lang), T(i.steal, lang)].join(' | ') + ' |');
        });
        out.push('');
      });
    });
  });

  out.push('## ' + L.checked + ' / ' + LABELS[lang === 'zh' ? 'en' : 'zh'].checked);
  out.push('');
  out.push(new Date(data.meta.date).toISOString().slice(0, 10) + ' &nbsp;|&nbsp; ' +
    (lang === 'zh' ? '生成物，请勿直接编辑' : 'generated, do not edit'));
  out.push('');
  L.footnote.forEach(f => out.push('- ' + f));
  out.push('');
  out.push('---');
  out.push('');
  out.push(L.intro);
  out.push('');
  return out.join('\n');
}

write('references/cases.md', markdownFor('zh'));
write('references/cases.en.md', markdownFor('en'));

/* ---------- 3. summary ---------- */

const byType = {};
items.forEach(i => { byType[i.type] = (byType[i.type] || 0) + 1; });

console.log('Visual Playbook build');
console.log('  categories :', data.categories.length);
console.log('  entries    :', items.length);
console.log('  links      :', new Set(items.map(i => i.url)).size);
console.log('  by type    :', JSON.stringify(byType));
console.log('  outputs    : gallery/index.html, references/cases.md, references/cases.en.md');
